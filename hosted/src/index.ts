function stripGoogleTokens<T extends Record<string, unknown>>(account: T): T {
  return {
    ...account,
    accessToken: null,
    refreshToken: null,
    idToken: null,
    accessTokenExpiresAt: null,
    refreshTokenExpiresAt: null,
  };
}

export function createAuth(env: Env) {
  return betterAuth({
    appName: "Locus",
    baseURL: env.BETTER_AUTH_URL,
    secret: env.BETTER_AUTH_SECRET,
    database: env.DB,
    trustedOrigins: [env.BETTER_AUTH_URL],
    account: {
      identityStrategy: "provider-id",
      accountLinking: { enabled: false },
    },
    databaseHooks: {
      account: {
        create: {
          before: async (account) => ({ data: stripGoogleTokens(account) }),
        },
        update: {
          before: async (account) => ({ data: stripGoogleTokens(account) }),
        },
      },
    },
    socialProviders: {
      google: {
        clientId: env.GOOGLE_CLIENT_ID,
        clientSecret: env.GOOGLE_CLIENT_SECRET,
        disableSignUp: registrationClosed(env),
      },
    },
    onAPIError: {
      errorURL: env.BETTER_AUTH_URL,
    },
    advanced: {
      useSecureCookies: env.BETTER_AUTH_URL.startsWith("https://"),
      database: {
        generateId: () => crypto.randomUUID(),
      },
    },
  });
}

export async function ensureLibrary(env: Env, userId: string, displayName: string): Promise<LibraryRow> {
  const existing = await findLibrary(env, userId);
  if (existing) return existing;

  const libraryId = crypto.randomUUID();
  const now = Date.now();
  const name = displayName ? `${displayName}'s Library` : "My Library";

  try {
    await env.DB.batch([
      env.DB.prepare(
        "INSERT INTO libraries (id, owner_user_id, name, created_at, updated_at) VALUES (?, ?, ?, ?, ?)",
      ).bind(libraryId, userId, name, now, now),
      env.DB.prepare(
        "INSERT INTO library_memberships (library_id, user_id, role, created_at) VALUES (?, ?, 'owner', ?)",
      ).bind(libraryId, userId, now),
    ]);
  } catch {
    // Concurrent first requests may race. Uniqueness constraints choose the
    // winner; re-reading gives both requests the same Library.
  }

  const created = await findLibrary(env, userId);
  if (!created) throw new Error("Could not provision a Library for this user");
  return created;
}

async function ensureAccess(env: Env, user: { id: string; email: string }): Promise<"active" | "disabled"> {
  const existing = await env.DB.prepare("SELECT status FROM user_access WHERE user_id = ?")
    .bind(user.id)
    .first<{ status: "active" | "disabled" }>();
  if (existing) return existing.status;

  try {
    await env.DB.prepare(
      "INSERT INTO user_access (user_id, email, status, created_at) VALUES (?, ?, 'active', ?)",
    )
      .bind(user.id, user.email.toLowerCase(), Date.now())
      .run();
    return "active";
  } catch {
    const raced = await env.DB.prepare("SELECT status FROM user_access WHERE user_id = ?")
      .bind(user.id)
      .first<{ status: "active" | "disabled" }>();
    if (raced) return raced.status;
    throw new Error("Could not provision access for this user");
  }
}

