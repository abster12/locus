function bearer(request: Request): string {
  const header = request.headers.get("authorization") ?? "";
  const match = /^Bearer\s+(\S+)/i.exec(header);
  return match?.[1] ?? "";
}

async function requireCaptureToken(request: Request, env: Env): Promise<CaptureToken | Response> {
  const offered = bearer(request);
  if (!offered) return json({ error: "missing token" }, 401);
  const token = await lookupToken(env.DB, offered);
  if (!token || token.revokedAt) return json({ error: "invalid token" }, 401);
  return token;
}

