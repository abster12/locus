function parseReadingQuery(url: URL): ReadingListQuery {
  const viewRaw = url.searchParams.get("view");
  const sortRaw = url.searchParams.get("sort");
  const view: ReadingView | undefined = viewRaw === "finished" || viewRaw === "queue" ? viewRaw : undefined;
  const sort: ReadingSort | undefined =
    sortRaw === "recent" ||
    sortRaw === "oldest" ||
    sortRaw === "shortest" ||
    sortRaw === "longest" ||
    sortRaw === "publication"
      ? sortRaw
      : undefined;
  const limitRaw = url.searchParams.get("limit");
  const limit = limitRaw ? Number(limitRaw) : undefined;
  const kind = url.searchParams.get("kind") ?? undefined;
  const source = url.searchParams.get("source") ?? undefined;
  const q = url.searchParams.get("q") ?? undefined;
  const cursor = url.searchParams.get("cursor") ?? undefined;
  return {
    ...(view ? { view } : {}),
    ...(kind ? { kind } : {}),
    ...(source ? { source } : {}),
    ...(q ? { q } : {}),
    ...(sort ? { sort } : {}),
    ...(cursor ? { cursor } : {}),
    ...(Number.isFinite(limit) ? { limit } : {}),
  };
}

function parseAgentReadingQuery(url: URL): ReadingListQuery {
  const limitRaw = url.searchParams.get("limit");
  return {
    view: (url.searchParams.get("view") ?? undefined) as ReadingView | undefined,
    kind: url.searchParams.get("kind") ?? undefined,
    source: url.searchParams.get("source") ?? undefined,
    q: url.searchParams.get("q") ?? undefined,
    sort: (url.searchParams.get("sort") ?? undefined) as ReadingSort | undefined,
    cursor: url.searchParams.get("cursor") ?? undefined,
    limit: limitRaw === null ? undefined : Number(limitRaw),
  };
}

