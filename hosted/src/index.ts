async function routeCapture(
  request: Request,
  env: Env,
  ctx: ExecutionContext,
): Promise<Response | null> {
  const url = new URL(request.url);
  const pathname = url.pathname;
  if (!isCapturePath(pathname)) return null;
  const db = env.DB;

  try {
    if (request.method === "POST" && pathname === "/capture/v1/hello") {
      const body = rec(await readJson(request));
      const offered = String(body.token ?? bearer(request) ?? "");
      const existing = offered ? await lookupToken(db, offered) : null;
      if (existing && !existing.revokedAt && existing.source === "*") {
        await heartbeat(db, existing.libraryId);
        return json({ token: offered, origin: env.BETTER_AUTH_URL });
      }
      return json({ error: "invalid token" }, 401);
    }

    if (request.method === "GET" && pathname === "/capture/v1/jobs/wait") {
      const auth = await requireCaptureToken(request, env);
      if (auth instanceof Response) return auth;
      const job = await waitJob(db, auth);
      if (!job) return new Response(null, { status: 204, headers: { "cache-control": "no-store" } });
      return json(jobDeliveryView(job));
    }

    const jobMatch = pathname.match(/^\/capture\/v1\/jobs\/([^/]+)(?:\/(progress|finish))?$/);
    if (jobMatch) {
      const jobId = decodeURIComponent(jobMatch[1]);
      const action = jobMatch[2];
      const auth = await requireCaptureToken(request, env);
      if (auth instanceof Response) return auth;
      const job = await getAccessibleJob(db, auth, jobId);
      if (request.method === "GET" && !action) {
        await touchJobLease(db, job);
        return json(jobStatusView(job));
      }
      if (request.method === "POST" && action === "progress") {
        const body = rec(await readJson(request));
        return json(
          await setJobProgress(db, job, {
            phase: String(body.phase ?? "capturing"),
            message: String(body.message ?? ""),
            seen: typeof body.seen === "number" ? body.seen : undefined,
            upserted: typeof body.upserted === "number" ? body.upserted : undefined,
          }),
        );
      }
      if (request.method === "POST" && action === "finish") {
        const body = rec(await readJson(request));
        await finishCaptureJob(db, job, {
          error: body.error ? String(body.error) : undefined,
          message: body.message ? String(body.message) : undefined,
          seen: typeof body.seen === "number" ? body.seen : undefined,
          upserted: typeof body.upserted === "number" ? body.upserted : undefined,
        });
        return json({ ok: true });
      }
    }

    if (request.method === "GET" && pathname === "/capture/v1/known") {
      const auth = await requireCaptureToken(request, env);
      if (auth instanceof Response) return auth;
      return json({ done: await knownCompleteIds(db, auth, url.searchParams.get("source")) });
    }

    if (request.method === "POST" && pathname === "/capture/v1/sessions") {
      const auth = await requireCaptureToken(request, env);
      if (auth instanceof Response) return auth;
      const grantJob = await jobForTokenId(db, auth.id);
      if (grantJob?.status === "cancelled") return json({ error: "job is cancelled" }, 403);
      const session = parseSession(await readJson(request));
      const started = await startSession(db, auth, session);
      if (auth.sourceAccountId && started.sourceAccountId !== auth.sourceAccountId && session.source) {
        await retargetJobs(db, String(session.source), auth.sourceAccountId, started.sourceAccountId);
      }
      return json(started);
    }

    if (request.method === "POST" && pathname === "/capture/v1/batches") {
      const auth = await requireCaptureToken(request, env);
      if (auth instanceof Response) return auth;
      const result = await ingestBatch(db, parseBatch(await readJson(request)), { token: auth });
      // Reading extract runs on the minute cron. Do not waitUntil-fetch here:
      // a hung X/Instagram fetch would stall the capture request and freeze the extension.
      return json(result);
    }

    if (request.method === "POST" && pathname === "/capture/v1/finish") {
      const auth = await requireCaptureToken(request, env);
      if (auth instanceof Response) return auth;
      const result = await finishSession(db, parseFinish(await readJson(request)), auth);
      return json(result);
    }

    return json({ error: "Not found" }, 404);
  } catch (error) {
    if (error instanceof RejectedPayload) return json({ error: error.message }, 400);
    if (error instanceof CaptureAuthorizationError) return json({ error: error.message }, error.statusCode);
    throw error;
  }
}

function expiresAt(value: Date | string): string {
  return value instanceof Date ? value.toISOString() : String(value);
}

async function route(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
  const url = new URL(request.url);
  const auth = createAuth(env);

  if (url.pathname.startsWith("/api/auth/")) {
    const scope = authRateLimitScope(request, url.pathname);
    if (scope) {
      const limited = await enforceRateLimit(request, env.AUTH_RATE_LIMITER, scope);
      if (limited) return limited;
    }
    return auth.handler(request);
  }

  if (url.pathname === "/mcp") {
    return routeMcp(request, env);
  }

  // Public Share Snapshot page. Deliberately outside /api/ and before auth:
  // no session, no cookie, no account. Revoked and unknown tokens get the
  // same empty 404 with no itinerary payload.
  if (request.method === "GET" && url.pathname.startsWith("/s/")) {
    let token = url.pathname.slice(3);
    try {
      token = decodeURIComponent(token);
    } catch {
      // Keep the raw slice; the lookup treats it as any other miss.
    }
    const shared = await findSharedSnapshot(env.DB, token);
    if (!shared) {
      return new Response(
        `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Link unavailable</title></head><body style="font-family:system-ui,sans-serif;color:#6b7176;background:#f1f2ef;margin:0"><main style="max-width:560px;margin:0 auto;padding:60px 20px"><p>This link is no longer available.</p></main></body></html>`,
        { status: 404, headers: { "content-type": "text/html; charset=utf-8" } },
      );
    }
    return new Response(renderShareHtml(shared.snapshot, shared.updatedAt), {
      status: 200,
      headers: { "content-type": "text/html; charset=utf-8" },
    });
  }

  if (isCapturePath(url.pathname)) {
    const response = await routeCapture(request, env, ctx);
    return response ?? json({ error: "Not found" }, 404);
  }

  if (request.method === "GET" && url.pathname === "/api/health") {
    return json({ ok: true });
  }

  if (request.method === "GET" && url.pathname === "/api/session") {
    const session = await auth.api.getSession({ headers: request.headers });
    if (!session) {
      return rejectedSessionResponse(request, env, json({ error: "Unauthorized" }, 401));
    }
    const access = await ensureAccess(env, session.user);
    if (access !== "active") {
      return rejectedSessionResponse(request, env, json({ error: "Forbidden" }, 403));
    }
    const library = await ensureLibrary(env, session.user.id, session.user.name);
    const token = await csrfToken(session.session.id, env.CSRF_SECRET);
    return json({
      user: {
        id: session.user.id,
        name: session.user.name,
        email: session.user.email,
        image: session.user.image ?? null,
      },
      session: {
        expiresAt: expiresAt(session.session.expiresAt),
      },
      library: {
        id: library.id,
        name: library.name,
        role: library.role,
      },
      csrfToken: token,
    });
  }

  const libraryId = libraryIdFromPath(url.pathname);
  if (libraryId && (request.method === "GET" || request.method === "POST")) {
    return withIdentity(request, env, auth, async (identity, library) => {
      if (libraryId !== identity.libraryId) return json({ error: "Not found" }, 404);
      return json({
        id: library.id,
        name: library.name,
        role: library.role,
      });
    });
  }

  if (isSourcesPath(request.method, url.pathname)) {
    return withIdentity(request, env, auth, async (identity) => {
      const response = await routeSources(request, env, identity);
      return response ?? json({ error: "Not found" }, 404);
    });
  }

  if (isDeskPath(request.method, url.pathname)) {
    return withIdentity(request, env, auth, async (identity) => {
      const response = await routeDesk(request, env, identity, ctx);
      return response ?? json({ error: "Not found" }, 404);
    });
  }

  if (isCapabilitiesPath(request.method, url.pathname)) {
    return withIdentity(request, env, auth, async (identity) => {
      const response = await routeCapabilities(request, env, identity);
      return response ?? json({ error: "Not found" }, 404);
    });
  }

  if (isReadingPath(request.method, url.pathname)) {
    return withIdentity(request, env, auth, async (identity) => {
      const response = await routeReading(request, env, identity, ctx);
      return response ?? json({ error: "Not found" }, 404);
    });
  }

  if (isKitchenPath(url.pathname)) {
    return withIdentity(request, env, auth, async (identity) => {
      const response = await routeKitchen(request, env, identity);
      return response ?? json({ error: "Not found" }, 404);
    });
  }

  if (isAtlasPath(url.pathname)) {
    return withIdentity(request, env, auth, async (identity) => {
      const response = await routeAtlas(request, env, identity);
      return response ?? json({ error: "Not found" }, 404);
    });
  }

  if (isTripsPath(url.pathname)) {
    return withIdentity(request, env, auth, async (identity) => {
      const response = await routeTrips(request, env, identity);
      return response ?? json({ error: "Not found" }, 404);
    });
  }

  if (url.pathname.startsWith("/api/")) {
    return json({ error: "Not found" }, 404);
  }
  return env.ASSETS.fetch(request);
}

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    const requestId = request.headers.get("cf-ray") ?? crypto.randomUUID();
    try {
      const response = applySecurityHeaders(await route(request, env, ctx), url);
      if (mayLogRequest(request, url)) {
        logEvent({
          level: "info",
          event: "request.complete",
          requestId,
          method: request.method,
          path: requestLogPath(url),
          status: response.status,
        });
      }
      return response;
    } catch {
      const response = applySecurityHeaders(json({ error: "Internal server error" }, 500), url);
      if (mayLogRequest(request, url)) {
        logEvent({
          level: "error",
          event: "request.failed",
          requestId,
          method: request.method,
          path: requestLogPath(url),
          status: 500,
          detail: "Unhandled Worker error",
        });
      }
      return response;
    }
  },
  async scheduled(_controller: ScheduledController, env: Env, ctx: ExecutionContext): Promise<void> {
    ctx.waitUntil(drainReading(env.DB));
  },
} satisfies ExportedHandler<Env>;
