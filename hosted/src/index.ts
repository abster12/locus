function bytesToBase64Url(bytes: ArrayBuffer): string {
  const bin = String.fromCharCode(...new Uint8Array(bytes));
  return btoa(bin).replaceAll("+", "-").replaceAll("/", "_").replaceAll("=", "");
}

async function hmac(secret: string, value: string): Promise<string> {
  const key = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const sig = await crypto.subtle.sign("HMAC", key, new TextEncoder().encode(value));
  return bytesToBase64Url(sig);
}

export async function csrfToken(sessionId: string, secret: string): Promise<string> {
  if (!secret || !sessionId) return "";
  return hmac(secret, sessionId);
}

async function timingSafeEqual(a: string, b: string): Promise<boolean> {
  const encoder = new TextEncoder();
  const [left, right] = await Promise.all([
    crypto.subtle.digest("SHA-256", encoder.encode(a)),
    crypto.subtle.digest("SHA-256", encoder.encode(b)),
  ]);
  const leftBytes = new Uint8Array(left);
  const rightBytes = new Uint8Array(right);
  let difference = 0;
  for (let index = 0; index < leftBytes.length; index++) {
    difference |= leftBytes[index] ^ rightBytes[index];
  }
  return difference === 0;
}

async function validCsrf(sessionId: string, token: string | null, secret: string): Promise<boolean> {
  if (!token || !secret) return false;
  const expected = await csrfToken(sessionId, secret);
  return expected.length > 0 && (await timingSafeEqual(token, expected));
}

async function requireMutationProtection(
  request: Request,
  env: Env,
  sessionId: string,
): Promise<Response | null> {
  if (request.headers.get("origin") !== env.BETTER_AUTH_URL) {
    return json({ error: "Forbidden" }, 403);
  }
  const token = request.headers.get("x-csrf-token");
  if (!(await validCsrf(sessionId, token, env.CSRF_SECRET))) {
    return json({ error: "Forbidden" }, 403);
  }
  return null;
}

export function redact(value: string): string {
  return value
    .replace(/[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/gi, "[redacted]")
    .replace(/((?:set-)?cookie\s*[:=]\s*)[^;\n]+/gi, "$1[redacted]")
    .replace(
      /\b(better-auth\.session_token|access_token|refresh_token|id_token|authorization|code|token)=([^&\s;]+)/gi,
      "$1=[redacted]",
    );
}

type LogLevel = "info" | "error";

export interface LogEvent {
  level: LogLevel;
  event: string;
  requestId: string;
  method: string;
  path: string;
  status: number;
  detail?: string;
  timestamp?: string;
}

export function logEvent(
  input: LogEvent,
  emit?: (line: string) => void,
): void {
  const record = {
    timestamp: input.timestamp ?? new Date().toISOString(),
    level: input.level,
    event: redact(input.event),
    requestId: redact(input.requestId),
    method: redact(input.method),
    path: redact(input.path.split("?", 1)[0]),
    status: input.status,
    ...(input.detail ? { detail: redact(input.detail) } : {}),
  };
  const line = JSON.stringify(record);
  if (emit) emit(line);
  else if (input.level === "error") console.error(line);
  else console.log(line);
}

